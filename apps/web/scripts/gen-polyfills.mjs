// Writes src/polyfills.ts: only the core-js stable modules the browserslist targets lack.
import { readFileSync, writeFileSync } from "node:fs"
import compat from "core-js-compat"

const pkg = JSON.parse(readFileSync("package.json", "utf8"))
const { list: needed } = compat({
  modules: ["core-js/stable"],
  targets: pkg.browserslist,
})
writeFileSync(
  new URL("../src/polyfills.ts", import.meta.url),
  `// Generated by scripts/gen-polyfills.mjs from package.json browserslist. Do not edit.\n` +
    needed.map(m => `import "core-js/modules/${m}.js"`).join("\n") +
    "\n",
)
